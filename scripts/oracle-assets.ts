// Writes lib/oracle-assets.ts: the coins from ParallaxPay's database that Binance trades against USDT.
// Run with: npx tsx scripts/oracle-assets.ts
import { writeFileSync } from 'node:fs'
import { CRYPTO_DATABASE } from '../lib/crypto-database'
import { binanceUsdtMarkets } from '../lib/market/binance'

// Same project, new ticker. (FTM to S and MKR to SKY are left out: those were conversions, not renames.)
const RENAMED: Record<string, string> = { MATIC: 'POL', RNDR: 'RENDER' }

const markets = await binanceUsdtMarkets()
const seen = new Set<string>()
const out: { symbol: string; name: string; category: string; market: string; rank?: number }[] = []
for (const c of CRYPTO_DATABASE) {
  if (c.category === 'STABLECOIN' || seen.has(c.symbol)) continue
  const base = RENAMED[c.symbol] ?? c.symbol
  const market = `${base}USDT`
  if (!markets.has(market)) continue
  seen.add(c.symbol)
  out.push({ symbol: c.symbol, name: c.name, category: c.category, market, rank: c.marketCapRank })
}
const ts = `// Generated by scripts/oracle-assets.ts on ${new Date().toISOString().slice(0, 10)}. Coins the Oracle covers:
// every one has a live Binance USDT market, so anyone can fetch the candles a call is judged on.
export type OracleAsset = { symbol: string; name: string; category: string; market: string; rank?: number }

export const ORACLE_ASSETS: OracleAsset[] = ${JSON.stringify(out, null, 2)}
`
writeFileSync('lib/oracle-assets.ts', ts)
console.log(`${out.length} of ${CRYPTO_DATABASE.length} coins have a Binance USDT market`)
console.log('missing:', CRYPTO_DATABASE.filter(c => !seen.has(c.symbol) && c.category !== 'STABLECOIN').map(c => c.symbol).join(' '))
