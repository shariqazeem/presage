// Copies contract ABIs from the Foundry build into lib/abi as typed constants.
// Run after `forge build`: node scripts/abi.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('..', import.meta.url).pathname
const contracts = ['CalledAgents', 'CalledLedger', 'CalledMarket']
for (const name of contracts) {
  const { abi } = JSON.parse(readFileSync(`${root}contracts/out/${name}.sol/${name}.json`, 'utf8'))
  const out = `// Generated by scripts/abi.mjs from contracts/out. Do not edit.\nexport const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const\n`
  writeFileSync(`${root}lib/abi/${name}.ts`, out)
  console.log(`lib/abi/${name}.ts  ${abi.length} entries`)
}
