// Writes lib/deployments.ts from contracts/deployments/<chainId>.json.
// Run after a deploy: node scripts/deployments.mjs
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'

const root = new URL('..', import.meta.url).pathname
// Pass a directory to generate from a rehearsal instead (e.g. contracts/deployments/fork).
const dir = process.argv[2] ? new URL(process.argv[2], `file://${root}`).pathname : `${root}contracts/deployments`
const out = {}
if (existsSync(dir)) {
  for (const f of readdirSync(dir).filter(f => /^\d+\.json$/.test(f))) {
    const d = JSON.parse(readFileSync(`${dir}/${f}`, 'utf8'))
    out[d.chainId] = {
      agents: d.agents,
      calls: d.calls,
      market: d.market,
      identityRegistry: d.identityRegistry,
      metisUsdFeed: d.metisUsdFeed,
      stables: d.stables,
      runner: d.runner,
      treasury: d.treasury,
      deployer: d.deployer,
      deployedAtBlock: d.deployedAtBlock,
    }
  }
}
const ts = `// Generated by scripts/deployments.mjs from contracts/deployments. Do not edit.
import type { Address } from 'viem'

export type Deployment = {
  agents: Address
  calls: Address
  market: Address
  identityRegistry: Address
  metisUsdFeed: Address
  stables: Address[]
  runner: Address
  treasury: Address
  deployer: Address
  deployedAtBlock: number
}

export const deployments: Record<number, Deployment> = ${JSON.stringify(out, null, 2)}
`
writeFileSync(`${root}lib/deployments.ts`, ts)
console.log('lib/deployments.ts', Object.keys(out).length ? `chains ${Object.keys(out).join(', ')}` : '(no deployments yet)')
